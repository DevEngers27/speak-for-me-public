/**
 * GitHub Actions workflow template: install -> (optional) Convex codegen drift
 * check -> lint -> typecheck -> test -> build.
 *
 * The workflow needs no secrets on purpose: it proves the credential-free
 * build path. Deploy and end-to-end jobs that need deploy keys belong in a
 * separate, environment-protected workflow.
 *
 * Output is plain YAML built from validated inputs; every scalar is emitted as
 * a JSON string (a valid YAML double-quoted scalar), so inputs cannot inject
 * keys or expressions.
 */

export type PackageManager = "pnpm" | "npm";

export interface CiWorkflowOptions {
  readonly name: string;
  readonly packageManager: PackageManager;
  /** Exact pnpm version installed globally when packageManager is "pnpm". */
  readonly pnpmVersion: string;
  readonly nodeVersionFile: string;
  readonly branches: readonly string[];
  /** package.json script names run in order. */
  readonly scripts: { readonly lint: string; readonly typecheck: string; readonly test: string; readonly build: string };
  /** When set, regenerates Convex code offline and fails if it differs from the committed copy. */
  readonly convexCodegenCheck: { readonly script: string; readonly generatedDir: string } | null;
  /** Non-secret job environment. */
  readonly env: Readonly<Record<string, string>>;
  readonly actions: { readonly checkout: string; readonly setupNode: string };
  readonly timeoutMinutes: number;
}

/**
 * Defaults follow the repository skeleton spike (pnpm 11.25.0, .node-version,
 * offline codegen drift check) and the original repo's action versions.
 */
export const DEFAULT_CI_OPTIONS: CiWorkflowOptions = Object.freeze({
  name: "CI",
  packageManager: "pnpm",
  pnpmVersion: "11.25.0",
  nodeVersionFile: ".node-version",
  branches: ["main"],
  scripts: { lint: "lint", typecheck: "typecheck", test: "test", build: "build" },
  convexCodegenCheck: { script: "convex:codegen:offline", generatedDir: "convex/_generated" },
  env: { NEXT_TELEMETRY_DISABLED: "1", CLERK_TELEMETRY_DISABLED: "1" },
  actions: { checkout: "actions/checkout@v7", setupNode: "actions/setup-node@v7" },
  timeoutMinutes: 20,
});

const SCRIPT_NAME = /^[a-z0-9][a-z0-9:_-]*$/;
const PATH = /^[A-Za-z0-9_.][A-Za-z0-9_./-]*$/;
const ENV_NAME = /^[A-Z_][A-Z0-9_]*$/;
const ACTION = /^[a-z0-9-]+\/[a-z0-9._-]+@[A-Za-z0-9._-]+$/;
const VERSION = /^\d+\.\d+\.\d+$/;
const BRANCH = /^[A-Za-z0-9._/-]+$/;

function q(value: string): string {
  return JSON.stringify(value);
}

function validate(o: CiWorkflowOptions): void {
  const fail = (msg: string): never => {
    throw new Error(`Invalid CI workflow options: ${msg}`);
  };
  for (const [key, script] of Object.entries(o.scripts)) {
    if (!SCRIPT_NAME.test(script)) fail(`scripts.${key}=${q(script)}`);
  }
  if (o.convexCodegenCheck) {
    if (!SCRIPT_NAME.test(o.convexCodegenCheck.script)) fail("convexCodegenCheck.script");
    if (!PATH.test(o.convexCodegenCheck.generatedDir) || o.convexCodegenCheck.generatedDir.includes("..")) {
      fail("convexCodegenCheck.generatedDir");
    }
  }
  if (o.packageManager === "pnpm" && !VERSION.test(o.pnpmVersion)) fail("pnpmVersion must be an exact x.y.z version");
  if (!PATH.test(o.nodeVersionFile)) fail("nodeVersionFile");
  if (o.branches.length === 0 || o.branches.some((b) => !BRANCH.test(b))) fail("branches");
  for (const [name, value] of Object.entries(o.env)) {
    if (!ENV_NAME.test(name)) fail(`env name ${q(name)}`);
    if (value.includes("${{")) fail(`env.${name} must not contain expressions`);
  }
  if (!ACTION.test(o.actions.checkout) || !ACTION.test(o.actions.setupNode)) fail("actions must be owner/repo@ref");
  if (!Number.isInteger(o.timeoutMinutes) || o.timeoutMinutes < 1 || o.timeoutMinutes > 360) fail("timeoutMinutes");
  if (!o.name.trim()) fail("name");
}

export function renderCiWorkflow(overrides: Partial<CiWorkflowOptions> = {}): string {
  const o: CiWorkflowOptions = { ...DEFAULT_CI_OPTIONS, ...overrides };
  validate(o);
  const pm = o.packageManager;
  const run = (script: string): string => (pm === "pnpm" ? `pnpm run ${script}` : `npm run ${script}`);
  const lines: string[] = [
    "# Generated by @speak-for-me/dev-tooling (src/ci/workflow.ts). Edit the options, not this file.",
    `name: ${q(o.name)}`,
    "on:",
    "  push:",
    `    branches: [${o.branches.map(q).join(", ")}]`,
    "  pull_request:",
    "permissions:",
    "  contents: read",
    "concurrency:",
    // Expression is fixed text, not user input.
    '  group: "ci-${{ github.ref }}"',
    "  cancel-in-progress: true",
    "jobs:",
    "  check:",
    "    runs-on: ubuntu-latest",
    `    timeout-minutes: ${o.timeoutMinutes}`,
  ];
  const envEntries = Object.entries(o.env);
  if (envEntries.length > 0) {
    lines.push("    env:");
    for (const [name, value] of envEntries) lines.push(`      ${name}: ${q(value)}`);
  }
  lines.push(
    "    steps:",
    `      - uses: ${o.actions.checkout}`,
    `      - uses: ${o.actions.setupNode}`,
    "        with:",
    `          node-version-file: ${q(o.nodeVersionFile)}`,
  );
  if (pm === "pnpm") {
    lines.push(`      - run: ${q(`npm install --global pnpm@${o.pnpmVersion}`)}`, `      - run: ${q("pnpm install --frozen-lockfile")}`);
  } else {
    lines.push(`      - run: ${q("npm ci")}`);
  }
  if (o.convexCodegenCheck) {
    lines.push(
      "      - name: Generated Convex code is committed and current",
      "        run: |",
      `          ${run(o.convexCodegenCheck.script)}`,
      `          git diff --exit-code -- ${o.convexCodegenCheck.generatedDir}`,
    );
  }
  lines.push(
    "      - name: Lint",
    `        run: ${q(run(o.scripts.lint))}`,
    "      - name: Typecheck",
    `        run: ${q(run(o.scripts.typecheck))}`,
    "      - name: Test",
    `        run: ${q(run(o.scripts.test))}`,
    "      # No secrets: proves the credential-free build path.",
    "      - name: Build",
    `        run: ${q(run(o.scripts.build))}`,
  );
  return `${lines.join("\n")}\n`;
}
